export function createPagedResponse<T>(content: T[], totalCount = content.length): PagedResponse<T> {
  return {
    code: 0,
    content,
    total_count: totalCount,
    total_page_count: Math.ceil(totalCount / 20) || 1,
    current_page: 0,
  };
}
